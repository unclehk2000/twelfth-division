import numpy as np, pandas as pd, statsmodels.formula.api as smf, warnings
warnings.filterwarnings('ignore')
D = pd.read_pickle('or2.pkl'); D = D[D.atr10.notna() & D.atr5.notna()].copy(); D['lor'] = np.log(D.or_atr)
cl = lambda v, a, b: np.clip(v, a, b); sig = lambda z: 100 / (1 + np.exp(-z))
pUp = lambda loc: sig(-2.780 + 5.457 * cl(loc, 0, 1))
pSide = lambda d, lor, v: sig(1.846 - 3.446 * cl(d, 0, 1) - 0.839 * lor + 0.663 * v)
pExt = lambda lor, v, l: sig(-1.392 - 1.180 * lor + 1.007 * v - 0.112 * l)
pOth = lambda lor, v, l: sig(-1.625 - 1.249 * lor + 0.792 * v - 0.109 * l)
A = D[D.bs != 0].assign(up1=lambda d: (d.bs == 1).astype(float), l=lambda d: d.loc959.clip(0, 1))
m = smf.logit('up1 ~ l', A).fit(disp=0); print('first', np.abs(m.predict(A) * 100 - pUp(A.l)).max().round(3))
S = pd.concat([D.assign(y=D.took_h.astype(float), d=1 - D.loc959.clip(0, 1)), D.assign(y=D.took_l.astype(float), d=D.loc959.clip(0, 1))])
m = smf.logit('y ~ d + lor + volr', S).fit(disp=0); print('side', np.abs(m.predict(S) * 100 - pSide(S.d, S.lor, S.volr)).max().round(3))
B = D[D.bs != 0].copy(); B['ltb'] = np.log(B.tbrk - 29); B['x1'] = B.x1.astype(float); B['fail'] = B.fail.astype(float)
m = smf.logit('x1 ~ lor + volr + ltb', B).fit(disp=0); print('ext', np.abs(m.predict(B) * 100 - pExt(B.lor, B.volr, B.ltb)).max().round(3))
m = smf.logit('fail ~ lor + volr + ltb', B).fit(disp=0); print('other', np.abs(m.predict(B) * 100 - pOth(B.lor, B.volr, B.ltb)).max().round(3))
# Pine's ltb = ln(max(0, minutes after 09:30 of the break bar - 30) + 1) == research ln(tbrk - 29)
print('ltb check', np.allclose(np.log(np.maximum(0, B.tbrk - 30) + 1), B.ltb))
# calibration of the side model by decile (all data)
S['p'] = pSide(S.d, S.lor, S.volr); S['dec'] = pd.qcut(S.p, 10, labels=False)
print(S.groupby('dec').agg(pred=('p', 'mean'), obs=('y', lambda s: 100 * s.mean())).round(1).T.to_string())
